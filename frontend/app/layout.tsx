import {createContext, useContext, useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';

import { me, logout } from '../lib/auth';
import { UserContext } from "./UserContext";

const inter = Inter({ subsets: ["latin"] });

const navMenu = [
  { route: '/', name: 'Top' },

];

type User = {
    id: number;
    name: string;
    email: string;
};

